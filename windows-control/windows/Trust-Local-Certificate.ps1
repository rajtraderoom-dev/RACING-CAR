. "$PSScriptRoot\Common.ps1"
Assert-Docker
$certificatePath=Wait-LocalCertificate
$certificate=New-Object System.Security.Cryptography.X509Certificates.X509Certificate2($certificatePath)
$existing=Get-ChildItem Cert:\CurrentUser\Root | Where-Object { $_.Thumbprint -eq $certificate.Thumbprint }
if ($existing) { Write-Host 'This local test CA is already trusted for your Windows account.'; exit 0 }
Write-Host "`nLOCAL HTTPS CERTIFICATE" -ForegroundColor Cyan
Write-Host "Subject: $($certificate.Subject)"
Write-Host "Thumbprint: $($certificate.Thumbprint)"
Write-Host 'This CA was generated by your local Docker gateway. Trust it only on this test computer.'
Write-Host 'It allows Edge/Chrome to use HTTPS localhost and Windows Hello. The private CA key stays in the Docker TLS volume.'
$answer=Read-Host 'Type TRUST to install this CA into your CurrentUser Root certificate store (anything else cancels)'
if ($answer -cne 'TRUST') { throw 'Certificate not installed. Re-run Trust-Local-Certificate.cmd when ready. Do not bypass browser certificate errors for passkey enrollment.' }
Import-Certificate -FilePath $certificatePath -CertStoreLocation Cert:\CurrentUser\Root | Out-Null
Write-Host 'Local test CA installed. Restart Edge/Chrome if it still shows an old certificate error.' -ForegroundColor Green
